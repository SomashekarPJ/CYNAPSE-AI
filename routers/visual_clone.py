# ---------------------------------------------------------------------------
# Helper: take screenshot with Playwright
# ---------------------------------------------------------------------------
async def capture_screenshot(url: str) -> Optional[bytes]:
    """Render the URL in a headless browser and return PNG bytes."""
    if not PLAYWRIGHT_AVAILABLE:
        return None
    try:
        async with async_playwright() as p:
            browser = await p.chromium.launch(headless=True)
            page = await browser.new_page(viewport={"width": 1280, "height": 720})
            await page.goto(url, timeout=15000, wait_until="domcontentloaded")
            await asyncio.sleep(2)  # let JS settle
            screenshot = await page.screenshot(full_page=False)
            await browser.close()
            return screenshot
    except Exception:
        return None


# ---------------------------------------------------------------------------
# Helper: fetch page HTML for text extraction
# ---------------------------------------------------------------------------
async def fetch_page_text(url: str) -> str:
    """Download raw HTML and extract visible text with BeautifulSoup."""
    import httpx
    try:
        async with httpx.AsyncClient(timeout=10, follow_redirects=True) as client:
            resp = await client.get(url, headers={"User-Agent": "Mozilla/5.0"})
            html = resp.text
    except Exception:
        return ""

    if not BS4_AVAILABLE:
        return html[:2000]

    soup = BeautifulSoup(html, "html.parser")
    # Remove scripts / styles
    for tag in soup(["script", "style", "noscript"]):
        tag.decompose()
    return soup.get_text(separator=" ", strip=True)[:3000]


# ---------------------------------------------------------------------------
# Helper: Groq text analysis for phishing indicators
# ---------------------------------------------------------------------------
def groq_phishing_analysis(page_text: str) -> dict:
    """Ask Groq to identify phishing indicators in the page text.
    Returns {"score": 0-100, "factors": [...]}.
    """
    if not GROQ_AVAILABLE or not page_text.strip():
        return {"score": 0, "factors": []}

    api_key = os.getenv("GROQ_API_KEY", "")
    if not api_key or api_key == "your_groq_key_here":
        return {"score": 0, "factors": ["Groq API key not configured"]}

    try:
        client = Groq(api_key=api_key)
        prompt = f"""You are a cybersecurity expert analysing web page text for phishing indicators.
Analyse the following text extracted from a website and determine if it contains phishing signals.

TEXT:
\"\"\"
{page_text[:2000]}
\"\"\"

Return your analysis as JSON with exactly these fields:
- "score": integer 0-100 (0 = clearly safe, 100 = clearly phishing)
- "factors": list of short strings describing each red flag found

Focus on: urgency language, credential harvesting prompts, impersonation of banks/govt,
misspellings of brand names, suspicious form fields asking for OTP/PIN/CVV,
fake security warnings, too-good-to-be-true offers.

Return ONLY valid JSON, no markdown."""

        resp = client.chat.completions.create(
            model="llama-3.3-70b-versatile",
            messages=[{"role": "user", "content": prompt}],
            temperature=0.1,
            max_tokens=500,
        )
        import json
        text = resp.choices[0].message.content.strip()
        # Try to extract JSON from response
        text = re.sub(r"```json\s*", "", text)
        text = re.sub(r"```\s*$", "", text)
        return json.loads(text)
    except Exception as e:
        return {"score": 0, "factors": [f"Groq analysis error: {str(e)}"]}


# ---------------------------------------------------------------------------
# Helper: pHash comparison
# ---------------------------------------------------------------------------
def compute_visual_similarity(screenshot_bytes: bytes) -> tuple[int, str]:
    """Compare screenshot pHash against fingerprint DB.
    Returns (similarity_score 0-100, matched_site_name).
    """
    if not IMAGEHASH_AVAILABLE or screenshot_bytes is None:
        return 0, "none"

    img = Image.open(io.BytesIO(screenshot_bytes))
    phash = imagehash.phash(img)

    best_score = 0
    best_site = "none"

    for site, stored_hex in LEGITIMATE_FINGERPRINTS.items():
        try:
            stored_hash = imagehash.hex_to_hash(stored_hex)
            hamming = phash - stored_hash  # Hamming distance (0 = identical)
            # Convert hamming distance to similarity %  (max distance ~64 for 64-bit hash)
            similarity = max(0, 100 - int((hamming / 64) * 100))
            if similarity > best_score:
                best_score = similarity
                best_site = site
        except Exception:
            continue

    return best_score, best_site


# ---------------------------------------------------------------------------
# Main endpoint
# ---------------------------------------------------------------------------
@router.post("/visual-clone", response_model=VisualCloneResponse)
async def analyze_visual_clone(req: VisualCloneRequest):
    """Analyse a URL for visual cloning of legitimate banking/govt sites."""

    url = req.url.strip()
    if not url.startswith(("http://", "https://")):
        url = "https://" + url

    # --- Cache check ---
    cache_key = f"vc:{hashlib.sha256(url.encode()).hexdigest()}"
    cached = cache_get(cache_key)
    if cached:
        return VisualCloneResponse(**cached)

    risk_factors: list[str] = []
    screenshot_url = ""

    # --- Layer 1: Visual pHash comparison ---
    screenshot_bytes = await capture_screenshot(url)
    if screenshot_bytes:
        # Save screenshot to a temp file
        os.makedirs("screenshots", exist_ok=True)
        fname = hashlib.md5(url.encode()).hexdigest() + ".png"
        spath = os.path.join("screenshots", fname)
        with open(spath, "wb") as f:
            f.write(screenshot_bytes)
        screenshot_url = f"/screenshots/{fname}"

        visual_score, matched_site = compute_visual_similarity(screenshot_bytes)
        if visual_score >= 60:
            risk_factors.append(
                f"Visual similarity {visual_score}% to {matched_site}"
            )
    else:
        visual_score = 0
        matched_site = "none"
        risk_factors.append("Could not capture screenshot — site may be down or blocking bots")

    # --- Layer 2: Groq text analysis ---
    page_text = await fetch_page_text(url)
    groq_result = groq_phishing_analysis(page_text)
    text_score = groq_result.get("score", 0)
    text_factors = groq_result.get("factors", [])
    risk_factors.extend(text_factors)

    # --- URL heuristic checks ---
    from urllib.parse import urlparse
    parsed = urlparse(url)
    domain = parsed.hostname or ""

    if len(domain) > 40:
        risk_factors.append("Unusually long domain name")
        text_score += 10

    if re.search(r"\d{4,}", domain):
        risk_factors.append("Domain contains long numeric sequence")
        text_score += 5

    if domain.count(".") > 3:
        risk_factors.append("Excessive subdomains")
        text_score += 5

    suspicious_tlds = [".xyz", ".top", ".buzz", ".click", ".tk", ".ml", ".ga", ".cf"]
    if any(domain.endswith(tld) for tld in suspicious_tlds):
        risk_factors.append(f"Suspicious TLD: {domain.split('.')[-1]}")
        text_score += 15

    # --- Combine scores (60% visual, 40% text) ---
    if visual_score > 0:
        final_score = clamp_score(visual_score * 0.6 + text_score * 0.4)
    else:
        # Can't do visual comparison — rely on text + heuristics
        final_score = clamp_score(text_score)

    verdict = get_verdict(final_score)

    # --- Store in DB ---
    input_hash = hashlib.sha256(url.encode()).hexdigest()
    await store_threat(
        feature="visual_clone",
        input_hash=input_hash,
        verdict=verdict,
        risk_score=final_score,
        evidence={"risk_factors": risk_factors},
    )

    # --- Broadcast via WebSocket ---
    await manager.broadcast({
        "type": "visual_clone",
        "verdict": verdict,
        "risk_score": final_score,
        "scam_type": "phishing_clone",
        "timestamp": __import__("datetime").datetime.now(
            __import__("datetime").timezone.utc
        ).isoformat(),
    })

    result = {
        "similarity_score": final_score,
        "verdict": verdict,
        "matched_site": matched_site,
        "risk_factors": risk_factors[:10],
        "screenshot_url": screenshot_url,
    }
    cache_set(cache_key, result)
    return VisualCloneResponse(**result)
